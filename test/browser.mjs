  assert.ok(await page.locator('#terminal-path').evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 14));
  assert.ok(await page.locator('.terminal-footer > span:last-child').evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 14));
