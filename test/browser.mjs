  mock.terminals[0].output('\x1b[?1000l\x1b[?1006l');
  await page.evaluate(() => { state.terminal.select(0, 0, 7); state.terminal.focus(); });
  await page.locator('.xterm-helper-textarea').press('Control+c');
  await page.waitForFunction(async () => (await navigator.clipboard.readText()) === 'Copilot');
  await page.locator('.xterm-helper-textarea').press('Control+Shift+C');
  await page.mouse.click(screen.x + 20, screen.y + cellHeight * 8);
  assert.equal(await page.locator('#selection-status').textContent(), '', 'A new terminal click clears stale cached text');
  await page.locator('.xterm-helper-textarea').press('Control+c');
  await page.locator('.xterm-helper-textarea').press('Control+c');
  await page.getByText('请先选中文字，或点击“复制终端文本”。Ctrl C 不会发送给 Copilot。').waitFor();
