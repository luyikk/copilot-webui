  const rows = await page.evaluate(() => state.terminal.rows);
  const cellWidth = screen.width / columns;
  const cellHeight = screen.height / rows;
  await page.evaluate(() => navigator.clipboard.writeText('ordinary drag must not copy'));
  await page.mouse.move(screen.x + 1, screen.y + cellHeight / 2);
  await page.mouse.down();
  await page.mouse.move(screen.x + cellWidth * 7, screen.y + cellHeight / 2, { steps: 12 });
  await page.mouse.up();
  assert.equal(await page.evaluate(() => state.terminal.getSelection()), 'Copilot', 'Mouse dragging selects actual terminal text');
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'ordinary drag must not copy');
  await page.evaluate(() => {
    window.originalClipboardWrite = navigator.clipboard.writeText.bind(navigator.clipboard);
    navigator.clipboard.writeText = async () => { throw new Error('Async clipboard disabled'); };
  });
