    const lastRow = await page.locator('.xterm-rows > div').last().boundingBox();
    const container = await page.locator('#terminal-container').boundingBox();
    assert.ok(lastRow.y + lastRow.height <= container.y + container.height + 1, 'Last terminal row must remain fully visible above the footer');
