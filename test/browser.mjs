import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { chromium } from 'playwright';
import { createApplication } from '../server.mjs';
import { mockTerminal } from './helpers.mjs';

const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'copilot-webui-browser-'));
const mock = mockTerminal();
let app, browser;
try {
  const home = path.join(temporary, 'home');
  await fs.mkdir(path.join(home, 'my-project'), { recursive: true });
  await fs.mkdir(path.join(home, '<img src=x onerror=alert(1)>'));
  app = await createApplication({ home, dataDir: path.join(temporary, 'state'), host: '127.0.0.1', port: 0, spawnPty: mock.spawn });
  const base = await app.listen();
  const key = (await fs.readFile(app.keyFile, 'utf8')).trim();
  const executablePath = process.env.CHROMIUM_PATH ?? chromium.executablePath();
  browser = await chromium.launch({ executablePath, headless: true, args: ['--disable-dev-shm-usage'] });
  const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  const externalRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => { if (!req.url().startsWith(base) && !req.url().startsWith('data:')) externalRequests.push(req.url()); });
  await page.goto(base);
  await page.locator('#login-view').waitFor({ state: 'visible' });
  await page.locator('#access-key').fill('wrong');
  await page.locator('#login-submit').click();
  await page.getByText('登录口令不正确。').waitFor();
  await page.locator('#access-key').fill(key);
  await page.locator('#login-submit').click();
  await page.locator('#welcome').waitFor({ state: 'visible' });
  assert.match(await page.title(), /Copilot Workspace/);
  await page.locator('#workspace-picker').click();
  await page.getByRole('button', { name: '<img src=x onerror=alert(1)>' }).waitFor();
  assert.equal(await page.locator('#directory-list img').count(), 0);
  await page.getByRole('button', { name: 'my-project', exact: true }).click();
  await page.locator('#choose-directory').click();
  assert.match(await page.locator('#selected-workspace').textContent(), /my-project$/);
  const screenshots = process.env.SCREENSHOT_DIR ?? path.resolve('test-results');
  await fs.mkdir(screenshots, { recursive: true });
  await page.screenshot({ path: path.join(screenshots, 'workspace-desktop.png'), fullPage: true, animations: 'disabled' });
  await page.locator('#start-session').click();
  await page.getByText('已连接', { exact: true }).waitFor();
  await page.locator('.xterm-helper-textarea').pressSequentially('hello from browser');
  await page.waitForFunction(() => document.querySelector('.xterm-screen')?.textContent.includes('hello from browser'));
  assert.match(mock.terminals[0].writes.join(''), /hello from browser/);
  assert.equal(mock.terminals[0].options.cwd, path.join(home, 'my-project'));
  await page.reload();
  await page.getByText('已连接', { exact: true }).waitFor();
  assert.equal(mock.terminals.length, 1, 'Refresh must reuse the live terminal');
  await page.waitForFunction(() => document.querySelector('.xterm-screen')?.textContent.includes('hello from browser'));
  await page.locator('#font-larger').click();
  assert.equal(await page.evaluate(() => localStorage.getItem('copilot-font-size')), '15');
  const sizeBefore = mock.terminals[0].sizes.at(-1);
  await page.setViewportSize({ width: 1100, height: 800 });
  await page.waitForTimeout(300);
  assert.notDeepEqual(mock.terminals[0].sizes.at(-1), sizeBefore);
  await page.locator('#new-session').click();
  await page.locator('#start-session').click();
  await page.getByText('已连接', { exact: true }).waitFor();
  assert.equal(mock.terminals.length, 2);
  await page.locator('.session-item').first().click();
  await page.getByText('已连接', { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.xterm-screen')?.textContent.includes('hello from browser'));
  await page.screenshot({ path: path.join(screenshots, 'terminal-desktop.png'), fullPage: true, animations: 'disabled' });
  await page.locator('#close-session').click();
  await page.locator('#cancel-close').click();
  assert.equal(mock.terminals[0].killed, false);
  await page.locator('#close-session').click();
  await page.locator('#confirm-close').click();
  await page.locator('#welcome').waitFor({ state: 'visible' });
  assert.equal(mock.terminals[0].killed, true);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(screenshots, 'workspace-mobile.png'), fullPage: true, animations: 'disabled' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'No mobile horizontal overflow');
  await page.locator('#menu-toggle').click();
  await page.locator('.session-item').click();
  await page.getByText('已连接', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Ctrl C', exact: true }).click();
  assert.ok(mock.terminals[1].writes.includes('\x03'));
  await page.screenshot({ path: path.join(screenshots, 'terminal-mobile.png'), fullPage: true, animations: 'disabled' });
  await page.locator('#menu-toggle').click();
  await page.locator('#logout').click();
  await page.locator('#login-view').waitFor({ state: 'visible' });
  assert.equal(mock.terminals[1].killed, false, 'Logout must not kill running work');
  assert.deepEqual(errors, [], `Browser errors: ${errors.join(', ')}`);
  assert.deepEqual(externalRequests, [], 'No third-party webpage requests');
  console.log('PASS: desktop/mobile login, safe directory picker, PTY I/O, reconnect, resize, multiple sessions, close confirmation, logout, and local-only resources.');
  console.log(`Screenshots: ${screenshots}`);
} finally {
  await browser?.close();
  await app?.close();
  await fs.rm(temporary, { recursive: true, force: true });
}
